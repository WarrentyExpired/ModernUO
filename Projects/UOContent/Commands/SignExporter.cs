        public static void Configure()
        {
            CommandSystem.Register("SignExport", AccessLevel.Developer, SignExport_OnCommand);
        }

        [Usage("SignExport")]
        [Description("Scans the world for signs and exports them to Data/signs_export.cfg")]
        public static void SignExport_OnCommand(CommandEventArgs c)
        {
            Export(c.Mobile);
        }

        public static void Export(Mobile from)
        {
            string filePath = Path.Combine(Core.BaseDirectory, "Data/signs_export.cfg");
            int count = 0;

            from.SendMessage("Scanning world for signs, please wait...");

            using (StreamWriter op = new StreamWriter(filePath))
            {
                foreach (Item item in World.Items.Values)
                {
                    if (item.Map == null || item.Map == Map.Internal)
                        continue;

                    int mapIndex = GetMapIndex(item.Map);

                    if (mapIndex == -1)
                        continue;

                    string text = "";

                    // Target 1: Programmed Sign objects (like those generated by SignGen)
                    if (item is Sign sign)
                    {
                        if (sign is LocalizedSign locSign)
                            text = "#" + locSign.Number;
                        else
                            text = sign.Name;
                    }
                    // Target 2: Generic Statics manually placed by builders using the GM Tool
                    else if (item is Static staticItem && _SignIDs.Contains(staticItem.ItemID))
                    {
                        text = staticItem.Name;
                    }
                    else
                    {
                        continue;
                    }

                    // Skip signs without custom names. A blank name will crash the importer later.
                    if (string.IsNullOrWhiteSpace(text) || text.Equals("Static", StringComparison.OrdinalIgnoreCase))
                        continue;

                    text = text.Replace("\n", " ").Replace("\r", "");

                    op.WriteLine($"{mapIndex} {item.ItemID} {item.X} {item.Y} {item.Z} {text}");
                    count++;
                }
            }

            from.SendMessage($"Sign export complete. {count} signs saved to Data/signs_export.cfg");
        }

        private static int GetMapIndex(Map map)
        {
            if (map == Map.Felucca) return 1;
            if (map == Map.Trammel) return 2;
            if (map == Map.Ilshenar) return 3;
            if (map == Map.Malas) return 4;
            if (map == Map.Tokuno) return 5;

            return -1;
        }
    }
