        public static Terrain GetTerrain(Map map, Point3D location, int x, int y)
        {
            if (map == Map.Internal || x < 0 || y < 0 || x >= map.Width || y >= map.Height)
                return Terrain.None;

            LandTile lTile = map.Tiles.GetLandTile(x, y);

            if (lTile.ID < _terrainLookup.Length)
            {
                Terrain t = _terrainLookup[lTile.ID];
                if (t != Terrain.None) return t;
            }

            return Terrain.None;
        }

        public static Terrain TestAround(Terrain ground, Map map, int x, int y, int distance)
        {
            Point3D p = new(9000, 9000, 0);
            Terrain terrain = Terrain.None;
            int tries = 8;

            while (tries > 0)
            {
                tries--;
                int g = Utility.Random(8);

                terrain = g switch
                {
                    0 => GetTerrain(map, p, x - distance, y - distance),
                    1 => GetTerrain(map, p, x, y - distance),
                    2 => GetTerrain(map, p, x + distance, y - distance),
                    3 => GetTerrain(map, p, x - distance, y),
                    4 => GetTerrain(map, p, x + distance, y),
                    5 => GetTerrain(map, p, x - distance, y + distance),
                    6 => GetTerrain(map, p, x, y + distance),
                    7 => GetTerrain(map, p, x + distance, y + distance),
                    _ => Terrain.None
                };

                if (terrain != Terrain.Water && terrain != Terrain.Cave && terrain != Terrain.Dirt && terrain != Terrain.Rock)
                    return terrain;
            }

            return ground;
        }

        public static Mobile RandomSpawn(Item spawn, Point3D loc, Map map)
        {
            Mobile m = null;
            spawn.MoveToWorld(loc, map);
            int tries = 100;

            Terrain terrain = GetTerrain(map, loc, spawn.X, spawn.Y);

            if (terrain != Terrain.Water && terrain != Terrain.Cave && terrain != Terrain.Dirt && terrain != Terrain.Rock)
                terrain = TestAround(terrain, map, spawn.X, spawn.Y, 15);

            while (m == null && tries > 0)
            {
                tries--;

                m = spawn switch
                {
                    SpawnCritters => terrain switch
                    {
                        Terrain.Water => Construct(WaterCritters),
                        Terrain.Cave => Construct(CaveCritters),
                        Terrain.Dirt => Construct(DirtCritters),
                        Terrain.Forest => Construct(ForestCritters),
                        Terrain.Grass => Construct(GrassCritters),
                        Terrain.Jungle => Construct(JungleCritters),
                        Terrain.Rock => Construct(RockCritters),
                        Terrain.Sand => Construct(SandCritters),
                        Terrain.Swamp => Construct(SwampCritters),
                        Terrain.Snow => Construct(SnowCritters),
                        _ => null
                    },
                    SpawnBirds => terrain switch
                    {
                        Terrain.Water => null, // Birds don't spawn in water
                        Terrain.Cave => Construct(CaveBirds),
                        Terrain.Dirt => Construct(DirtBirds),
                        Terrain.Forest => Construct(ForestBirds),
                        Terrain.Grass => Construct(GrassBirds),
                        Terrain.Jungle => Construct(JungleBirds),
                        Terrain.Rock => Construct(RockBirds),
                        Terrain.Sand => Construct(DesertBirds),
                        Terrain.Swamp => Construct(SwampBirds),
                        Terrain.Snow => Construct(SnowBirds),
                        _ => null
                    },
                    SpawnAnimals => terrain switch
                    {
                        Terrain.Water => null, // Land animals don't spawn in water
                        Terrain.Cave => Construct(CaveAnimals),
                        Terrain.Dirt => Construct(DirtAnimals),
                        Terrain.Forest => Construct(ForestAnimals),
                        Terrain.Grass => Construct(GrassAnimals),
                        Terrain.Jungle => Construct(JungleAnimals),
                        Terrain.Rock => Construct(RockAnimals),
                        Terrain.Sand => Construct(SandAnimals),
                        Terrain.Swamp => Construct(SwampAnimals),
                        Terrain.Snow => Construct(SnowAnimals),
                        _ => null
                    },
                    SpawnMobs => terrain switch
                    {
                        Terrain.Water => null,
                        Terrain.Cave => null,
                        Terrain.Dirt => null,
                        Terrain.Forest => Construct(ForestMobs),
                        Terrain.Grass => Construct(GrassMobs),
                        Terrain.Jungle => Construct(JungleMobs),
                        Terrain.Rock => null,
                        Terrain.Sand => Construct(SandMobs),
                        Terrain.Swamp => Construct(SwampMobs),
                        Terrain.Snow => Construct(SnowMobs),
                        _ => null
                    },
                };
            }

            return m;
        }

        public static Mobile Construct(Type[] types)
        {
            if (types.Length > 0)
            {
                Type typeToSpawn = types[Utility.Random(types.Length)];
                try
                {
                    return Activator.CreateInstance(typeToSpawn) as Mobile;
                }
                catch
                {
                    return null;
                }
            }
            return null;
        }
